export let lang = localStorage.getItem("rz_lang") || "en";
export function t(k, vars) {
  let s = (STR[lang] && STR[lang][k]) || (STR.en && STR.en[k]) || k;
  if (vars) {
    for (const key of Object.keys(vars)) {
      s = s.split("{" + key + "}").join(String(vars[key]));
    }
  }
  return s;
}
export function setLang(l) {
  lang = l; localStorage.setItem("rz_lang", l);
  document.documentElement.lang = l === "en" ? "en" : (l === "zh" ? "zh-CN" : "zh-TW");
}
